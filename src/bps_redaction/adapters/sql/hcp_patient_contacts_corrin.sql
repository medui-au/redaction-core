SELECT DISTINCT
    con.CONTACTID,
    con.SURNAME,
    con.FIRSTNAME,
    cat.CATEGORYNAME,
    cat.CATEGORYCODE
FROM dbo.CORRESPONDENCEIN c
LEFT JOIN dbo.CONTACTS con
    ON c.CONTACTID = con.CONTACTID
LEFT JOIN dbo.CATEGORIES cat
    ON con.CATEGORYCODE = cat.CATEGORYCODE
WHERE c.InternalId = :patient_id
  AND con.SURNAME IS NOT NULL
  AND LEN(RTRIM(con.SURNAME)) > 0

SELECT DISTINCT
    dbo.CONTACTS.CONTACTID,
    dbo.CONTACTS.SURNAME,
    dbo.CONTACTS.FIRSTNAME,
    dbo.CATEGORIES.CATEGORYNAME,
    dbo.CATEGORIES.CATEGORYCODE
FROM dbo.CORRESPONDENCEOUT
INNER JOIN dbo.CONTACTS
    ON dbo.CORRESPONDENCEOUT.CONTACTID = dbo.CONTACTS.CONTACTID
INNER JOIN dbo.CATEGORIES
    ON dbo.CONTACTS.CATEGORYCODE = dbo.CATEGORIES.CATEGORYCODE
WHERE dbo.CORRESPONDENCEOUT.INTERNALID = :patient_id
  AND dbo.CONTACTS.SURNAME IS NOT NULL
  AND LEN(RTRIM(dbo.CONTACTS.SURNAME)) > 0
